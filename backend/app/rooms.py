# Every room, retired ones too; style_rooms gives the ones offered for new samples.
STYLE_ROOMS: dict[str, tuple[Room, ...]] = {'french_couture': _FRENCH_COUTURE_ROOMS, 'minimal_bridal': _MINIMAL_BRIDAL_ROOMS,
                                            'forest_film': _FOREST_FILM_ROOMS, 'city_story': _CITY_STORY_ROOMS,
                                            'chinese_celebration': _CHINESE_CELEBRATION_ROOMS,
                                            'garden_lawn': _GARDEN_LAWN_ROOMS,
                                            'flower_house': _FLOWER_HOUSE_ROOMS,
                                            'seaside_sunset': _SEASIDE_ROOMS}


def style_rooms(style_id: str) -> tuple[Room, ...]:
    """The rooms offered for new samples (V7.58: not the retired ones)."""
    return tuple(room for room in STYLE_ROOMS.get(style_id, ()) if not room.retired)


def has_rooms(style_id: str) -> bool:
    return bool(style_rooms(style_id))


def get_room(style_id: str, room_id: str | None) -> Room | None:
    """Any room of the style, retired ones too: a picture shot in a retired room keeps it."""
    return next((room for room in STYLE_ROOMS.get(style_id, ()) if room.id == room_id), None)


def default_room(style_id: str) -> str | None:
    """The room a sample is shot in when none is picked: the style's first."""
    rooms = style_rooms(style_id)
    return rooms[0].id if rooms else None


def room_area(style_id: str, room_id: str, area: int) -> RoomArea:
    """Area number `area` (from 1) of the room; ValueError for a room or number the style does not have."""
    room = get_room(style_id, room_id)
    if room is None or not 1 <= area <= len(room.areas):
        raise ValueError(f'unknown room area {style_id}/{room_id}/{area}')
    return room.areas[area - 1]


def room_image_version(style_id: str, room_id: str) -> int:
    """The version of the room's picture that its style arts are made from (V7.57: per room)."""
    room = get_room(style_id, room_id)
    return room.image_version if room is not None and room.image_version is not None else ROOM_IMAGE_VERSION


def main_image(style_id: str, room_id: str) -> Path:
    """The room's main picture (area 1), kept in the repository."""
    return ROOM_IMAGE_DIR / style_id / room_id / f'1_{room_area(style_id, room_id, 1).id}.jpg'
