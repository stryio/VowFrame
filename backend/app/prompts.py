def with_hands_and_wash(prompt: str) -> str:
    """A face fix prompt that also fixes the hands and washes the picture (V7.32)."""
    parts = prompt.split('\n\n')
    return '\n\n'.join((*parts[:-1], *FIX_HANDS_AND_WASH, parts[-1]))


